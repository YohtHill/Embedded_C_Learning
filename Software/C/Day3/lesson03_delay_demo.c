/*
 * 任务 3：演示 char 做延时计数为什么死循环
 *
 * 注意：这里用「安全演示」方式——不真的写死循环卡住电脑，
 * 而是观察 char 计数到 127 之后发生了什么。
 */

#include <stdio.h>

int main() {
    printf("===== 用 char 做延时计数会怎样？=====\n\n");

    /* 模拟延时循环：目标是 i 到 1000（char 做不到，会溢出） */
    char i = 0;                 /* char 范围：-128 ~ 127 */
    int count = 0;

    while (i < 1000) {          /* 假设延时目标是 i 到 1000 */
        count++;
        i++;                    /* i 每次加 1 */

        /* 每 20 次打印一次，观察 i 的变化 */
        if (count % 20 == 0) {
            printf("第 %3d 次：i = %d\n", count, (int)i);
        }

        /* 安全保护：最多跑 150 次，防止程序卡死 */
        if (count > 150) {
            printf("\n>>> 已跑超过 150 次，强行停止（否则会死循环！）\n");
            break;
        }
    }

    printf("\n===== 分析 =====\n");
    printf("char 最大只能到 127\n");
    printf("i 加到 127 后再 +1，就会溢出变成负数\n");
    printf("负数永远 < 1000，所以循环条件 i<1000 永远成立 → 死循环！\n");

    return 0;
}
